  constructor() {
    const storedLang = this.safeGet(this.langKey);
    const storedCurr = this.safeGet(this.currencyKey);
    if (storedLang && this.supportedLanguages.includes(storedLang as any)) {
      this.language.set(storedLang as any);
    }
    if (storedCurr && this.supportedCurrencies.includes(storedCurr as any)) {
      this.currency.set(storedCurr as any);
    }
  }

  t(key: string): string {
    return this.translations[this.language()]?.[key] || this.translations['en']?.[key] || key;
  }

  setLanguage(lang: 'en' | 'pt' | 'de') {
    this.language.set(lang);
    this.safeSet(this.langKey, lang);
  }

  setCurrency(curr: 'USD' | 'EUR' | 'GBP' | 'BRL') {
    this.currency.set(curr);
    this.safeSet(this.currencyKey, curr);
  }

  languageLabel(lang: 'en' | 'pt' | 'de' = this.language()): string {
    const key = `nav.language.${lang}`;
    const translated = this.translations[this.language()]?.[key] ?? this.translations['en']?.[key];
    return translated ?? (lang === 'de' ? 'Deutsch' : lang === 'pt' ? 'Português' : 'English');
  }

  formatPrice(amount: number): string {
    const locale = this.language() === 'de' ? 'de-DE' : this.language() === 'pt' ? 'pt-PT' : 'en-US';
    const formatter = new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: this.currency()
    });
    return formatter.format(amount);
  }

  formatDate(isoOrDate: any): string {
    const dt = this.toDate(isoOrDate);
    if (!dt) return '-';
    const locale = this.language() === 'de' ? 'de-DE' : this.language() === 'pt' ? 'pt-PT' : 'en-US';
    return new Intl.DateTimeFormat(locale, { year: 'numeric', month: 'short', day: '2-digit' }).format(dt);
  }

  formatTime(isoOrDate: any): string {
    const dt = this.toDate(isoOrDate);
    if (!dt) return '-';
    const locale = this.language() === 'de' ? 'de-DE' : this.language() === 'pt' ? 'pt-PT' : 'en-US';
    return new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit' }).format(dt);
  }

  formatDateTime(isoOrDate: any): string {
    const dt = this.toDate(isoOrDate);
    if (!dt) return '-';
    const locale = this.language() === 'de' ? 'de-DE' : this.language() === 'pt' ? 'pt-PT' : 'en-US';
    return new Intl.DateTimeFormat(locale, { year: 'numeric', month: 'short', day: '2-digit', hour: '2-digit', minute: '2-digit' }).format(dt);
  }

  private toDate(v: any): Date | null {
    if (!v) return null;
    if (v instanceof Date) return isNaN(v.getTime()) ? null : v;
    const d = new Date(String(v));
    return isNaN(d.getTime()) ? null : d;
  }

  private safeGet(key: string): string | null {
    try {
      return localStorage.getItem(key);
    } catch {
      return null;
    }
  }

  private safeSet(key: string, value: string) {
    try {
      localStorage.setItem(key, value);
    } catch { }
  }
